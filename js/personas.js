function pick(values) {
  return values[Math.floor(Math.random() * values.length)];
}

export function generatePersona(min, max, locale) {
  if (!Number.isInteger(min) || !Number.isInteger(max) || min < 0 || max > 120 || min > max) {
    throw new Error("Укажите целые числа от 0 до 120 и проверьте порядок границ.");
  }
  const age = min + Math.floor(Math.random() * (max - min + 1));
  const [firstNames, surnames] = pick(Object.hasOwn(names, locale) ? names[locale] : names.uk);
  const personality = age < 3 ? youngPersonalities[0]
    : age < 7 ? youngPersonalities[1]
    : age < 13 ? youngPersonalities[2] : pick(personalities);
  return {
    id: crypto.randomUUID(),
    name: `${pick(firstNames)} ${pick(surnames)}`,
    age,
    ...personality,
    createdAt: new Date().toISOString(),
    mailboxId: null,
  };
}
